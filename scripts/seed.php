$randSize = fn(int $min, int $max) => random_int($min * 1024, $max * 1024);
$now = time();
$count = 0;

foreach ($items as $i => [$course, $tags, $title, $summary, $type, $fileNames]) {
    $files = [];
    $total = 0;
    foreach ($fileNames as $name) {
        $ext = $type === 'zip' ? 'zip' : ($type === 'mp4' ? 'mp4' : $type);
        $size = match ($type) {
            'mp4'   => $randSize(80000, 300000),
            'zip'   => $randSize(3000, 40000),
            'ppt'   => $randSize(1500, 9000),
            default => $randSize(400, 6000),
        };
        $files[] = ['name' => "{$name}.{$ext}", 'size' => $size];
        $total += $size;
    }
    $published = $now - random_int(3, 700) * 86400 - random_int(0, 86399);
    $downloads = random_int(20, 9000);

    $stmt = $pdo->prepare(
        'INSERT INTO materials(id, title, summary, course, tags, file_type, file_size, files, downloads, published_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)'
    );
    $stmt->execute([
        $i + 1, $title, $summary, $course, $tags, $type, $total,
        json_encode($files, JSON_UNESCAPED_UNICODE), $downloads, $published,
    ]);
    $count++;
}

